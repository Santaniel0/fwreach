// Package iptables compiles iptables-save and ip6tables-save output into
// the rule IR. It reads both the legacy and the nf_tables flavour; the
// text format is the same, only the kernel side differs.
package iptables

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"net/netip"
	"strconv"
	"strings"

	"github.com/Santaniel0/fwreach/internal/netpkt"
	"github.com/Santaniel0/fwreach/internal/ruleset"
)

// ErrSyntax is returned for lines that are not valid iptables-save output.
var ErrSyntax = errors.New("iptables-save syntax error")

// Result is a parsed dump.
type Result struct {
	Tables   []*ruleset.Table
	Source   ruleset.Source
	Warnings []string
}

// builtinChain returns how x_tables attaches a built-in chain: its hook,
// type and the priority the kernel registers it with. iptables-nft creates
// base chains with the same values.
func builtinChain(table, chain string) (ruleset.BaseChain, bool) {
	hook, ok := netpkt.ParseHook(strings.ToLower(chain))
	if !ok {
		return ruleset.BaseChain{}, false
	}
	b := ruleset.BaseChain{Hook: hook, Kind: ruleset.KindFilter}
	switch table {
	case "raw":
		b.Priority = -300
		ok = hook == netpkt.Prerouting || hook == netpkt.Output
	case "mangle":
		b.Priority = -150
		if hook == netpkt.Output {
			b.Kind = ruleset.KindRoute
		}
	case "nat":
		b.Kind, b.Priority = ruleset.KindNAT, -100
		if hook == netpkt.Input || hook == netpkt.Postrouting {
			b.Priority = 100
		}
		ok = hook != netpkt.Forward
	case "filter", "security":
		if table == "security" {
			b.Priority = 50
		}
		ok = hook == netpkt.Input || hook == netpkt.Forward || hook == netpkt.Output
	default:
		ok = false
	}
	return b, ok
}

// Parse reads a dump for one address family. forced overrides the backend
// detection from the header comment when non-zero.
func Parse(r io.Reader, fam netpkt.Family, forced ruleset.Source) (*Result, error) {
	res := &Result{Source: forced}
	tfam := ruleset.FamilyIP
	if fam == netpkt.IPv6 {
		tfam = ruleset.FamilyIP6
	}
	var cur *ruleset.Table
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "[") {
			if i := strings.Index(line, "]"); i > 0 {
				line = strings.TrimSpace(line[i+1:])
			}
		}
		switch {
		case line == "":
		case strings.HasPrefix(line, "#"):
			res.noteComment(line)
		case strings.HasPrefix(line, "*"):
			cur = &ruleset.Table{Family: tfam, Name: line[1:]}
			res.Tables = append(res.Tables, cur)
		case line == "COMMIT":
			cur = nil
		case cur == nil:
			return nil, fmt.Errorf("line %d: %w: %q outside a table", n, ErrSyntax, line)
		case strings.HasPrefix(line, ":"):
			if err := declareChain(cur, line[1:]); err != nil {
				return nil, fmt.Errorf("line %d: %w", n, err)
			}
		case strings.HasPrefix(line, "-A "):
			name, spec, _ := strings.Cut(line[3:], " ")
			c := cur.Chain(name)
			if c == nil {
				return nil, fmt.Errorf("line %d: %w: rule for undeclared chain %q", n, ErrSyntax, name)
			}
			rule, err := ParseRule(spec, fam)
			if err != nil {
				return nil, fmt.Errorf("line %d: %w", n, err)
			}
			rule.Pos = len(c.Rules) + 1
			c.Rules = append(c.Rules, rule)
		default:
			return nil, fmt.Errorf("line %d: %w: %q", n, ErrSyntax, line)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("read iptables-save: %w", err)
	}
	if res.Source == 0 {
		res.Source = ruleset.SourceIPTablesNft
		res.Warnings = append(res.Warnings, "iptables backend not stated in the dump header; assuming nf_tables")
	}
	for _, t := range res.Tables {
		t.Source = res.Source
		for _, c := range t.Chains {
			for i, r := range c.Rules {
				a := r.Action
				if (a.Kind == ruleset.ActJump || a.Kind == ruleset.ActGoto) && t.Chain(a.Target) == nil {
					c.Rules[i].Action = ruleset.Action{Kind: ruleset.ActUnknown, What: "target " + a.Target}
				}
			}
		}
	}
	return res, nil
}

func (res *Result) noteComment(line string) {
	switch {
	case strings.Contains(line, "legacy tables present"):
		res.Warnings = append(res.Warnings, "dump says legacy iptables tables are also loaded; collect iptables-legacy-save too")
	case !strings.HasPrefix(line, "# Generated by") || res.Source != 0:
	case strings.Contains(line, "nf_tables") || strings.Contains(line, "-nft-"):
		res.Source = ruleset.SourceIPTablesNft
	case strings.Contains(line, "legacy"):
		res.Source = ruleset.SourceIPTablesLegacy
	}
}

func declareChain(t *ruleset.Table, decl string) error {
	f := strings.Fields(decl)
	if len(f) < 2 {
		return fmt.Errorf("%w: chain declaration %q", ErrSyntax, decl)
	}
	c := &ruleset.Chain{Name: f[0]}
	if b, ok := builtinChain(t.Name, f[0]); ok {
		switch f[1] {
		case "ACCEPT":
			b.Policy = ruleset.Accept
		case "DROP":
			b.Policy = ruleset.Drop
		default:
			return fmt.Errorf("%w: policy %q", ErrSyntax, f[1])
		}
		c.Base = &b
	}
	t.Chains = append(t.Chains, c)
	return nil
}

type option struct {
	name   string
	negate bool
	args   []string
}

// ParseRule compiles the part of a rule after "-A CHAIN", for example
// "-p tcp -m tcp --dport 22 -j ACCEPT".
func ParseRule(spec string, fam netpkt.Family) (ruleset.Rule, error) {
	toks, err := split(spec)
	if err != nil {
		return ruleset.Rule{}, err
	}
	var opts []option
	neg := false
	for _, tok := range toks {
		switch {
		case tok == "!":
			neg = true
		case strings.HasPrefix(tok, "-") && len(tok) > 1:
			opts = append(opts, option{name: tok, negate: neg})
			neg = false
		case len(opts) == 0:
			return ruleset.Rule{}, fmt.Errorf("%w: unexpected %q in %q", ErrSyntax, tok, spec)
		default:
			opts[len(opts)-1].args = append(opts[len(opts)-1].args, tok)
		}
	}
	rule := ruleset.Rule{Text: spec, Action: ruleset.Action{Kind: ruleset.ActContinue}}
	module := ""
	unknownModules := map[string]bool{}
	for i := 0; i < len(opts); i++ {
		o := opts[i]
		if o.name == "-m" || o.name == "--match" {
			module = strings.Join(o.args, " ")
		}
		if o.name == "-j" || o.name == "--jump" || o.name == "-g" || o.name == "--goto" {
			if len(o.args) != 1 {
				return ruleset.Rule{}, fmt.Errorf("%w: %s needs a target in %q", ErrSyntax, o.name, spec)
			}
			rule.Action, err = target(o.args[0], o.name == "-g" || o.name == "--goto", opts[i+1:], fam)
			if err != nil {
				return ruleset.Rule{}, fmt.Errorf("%q: %w", spec, err)
			}
			break
		}
		m, err := match(o, fam)
		if err != nil {
			return ruleset.Rule{}, fmt.Errorf("%q: %w", spec, err)
		}
		if u, ok := m.(ruleset.UnknownMatch); ok && module != "" {
			if unknownModules[module] {
				continue
			}
			unknownModules[module] = true
			u.What = "-m " + module + " " + u.What
			m = u
		}
		if m != nil {
			rule.Matches = append(rule.Matches, m)
		}
	}
	return rule, nil
}

func arg(o option) (string, error) {
	if len(o.args) != 1 {
		return "", fmt.Errorf("%w: %s takes one argument, got %v", ErrSyntax, o.name, o.args)
	}
	return o.args[0], nil
}

// match returns nil for options that never affect a NEW inbound packet,
// such as comments and the -m that introduces a module.
func match(o option, fam netpkt.Family) (ruleset.Match, error) {
	switch o.name {
	case "-m", "--match", "--comment", "--limit-burst", "--limit-iface-in", "--limit-iface-out":
		return nil, nil
	case "-s", "--source", "-d", "--destination", "--ctorigdst", "--ctorigsrc":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		ps, err := prefixes(v, fam)
		if err != nil {
			return nil, err
		}
		m := ruleset.AddrMatch{Dir: ruleset.DirSrc, Family: fam, Prefixes: ps, Negate: o.negate}
		switch o.name {
		case "-d", "--destination":
			m.Dir = ruleset.DirDst
		case "--ctorigdst":
			m.Dir, m.OrigDst = ruleset.DirDst, true
		}
		return m, nil
	case "-i", "--in-interface", "-o", "--out-interface":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		name, wild := strings.CutSuffix(v, "+")
		return ruleset.IfaceMatch{Out: o.name == "-o" || o.name == "--out-interface", Name: name, Pattern: wild, Negate: o.negate}, nil
	case "-p", "--protocol":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		if v == "all" || v == "0" {
			return nil, nil
		}
		p, err := netpkt.ParseProto(v)
		if err != nil {
			return nil, fmt.Errorf("%w: %w", ErrSyntax, err)
		}
		return ruleset.ProtoMatch{Protos: []netpkt.Proto{p}, Negate: o.negate}, nil
	case "--dport", "--destination-port", "--sport", "--source-port", "--dports", "--destination-ports",
		"--sports", "--source-ports", "--ctorigdstport":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		rs, err := ports(v)
		if err != nil {
			return nil, err
		}
		m := ruleset.PortMatch{Dir: ruleset.DirDst, Ranges: rs, Negate: o.negate, OrigDst: o.name == "--ctorigdstport"}
		if strings.HasPrefix(o.name, "--s") {
			m.Dir = ruleset.DirSrc
		}
		return m, nil
	case "--state", "--ctstate":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		var st ruleset.CtState
		for _, s := range strings.Split(v, ",") {
			bit, ok := ruleset.ParseCtState(s)
			if !ok {
				return nil, fmt.Errorf("%w: conntrack state %q", ErrSyntax, s)
			}
			st |= bit
		}
		return ruleset.CtStateMatch{States: st, Negate: o.negate}, nil
	case "--ctdir":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		return ruleset.FixedMatch{Matches: (v == "ORIGINAL") != o.negate, Why: "--ctdir " + v}, nil
	case "--dst-type", "--src-type":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		var types netpkt.AddrType
		for _, s := range strings.Split(v, ",") {
			switch s {
			case "LOCAL":
				types |= netpkt.AddrLocal
			case "UNICAST":
				types |= netpkt.AddrUnicast
			case "BROADCAST":
				types |= netpkt.AddrBroadcast
			case "MULTICAST":
				types |= netpkt.AddrMulticast
			default:
				return ruleset.UnknownMatch{What: "addrtype " + s}, nil
			}
		}
		dir := ruleset.DirDst
		if o.name == "--src-type" {
			dir = ruleset.DirSrc
		}
		return ruleset.AddrTypeMatch{Dir: dir, Types: types, Negate: o.negate}, nil
	case "--mark":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		val, mask, err := markValue(v)
		if err != nil {
			return nil, err
		}
		return ruleset.MarkMatch{Value: val, Mask: mask, Negate: o.negate}, nil
	case "--icmp-type", "--icmpv6-type", "-f", "--fragment":
		return ruleset.FixedMatch{Why: o.name + " never matches a TCP or UDP connection start"}, nil
	case "--syn":
		return ruleset.ProtoMatch{Protos: []netpkt.Proto{netpkt.ProtoTCP}, Negate: o.negate}, nil
	case "--pkt-type":
		v, err := arg(o)
		if err != nil {
			return nil, err
		}
		return ruleset.FixedMatch{Matches: (v == "unicast") != o.negate, Why: "--pkt-type " + v}, nil
	}
	return ruleset.UnknownMatch{What: strings.TrimSpace(o.name + " " + strings.Join(o.args, " "))}, nil
}

func target(name string, isGoto bool, opts []option, fam netpkt.Family) (ruleset.Action, error) {
	switch name {
	case "ACCEPT":
		return ruleset.Action{Kind: ruleset.ActVerdict, Verdict: ruleset.Accept}, nil
	case "DROP":
		return ruleset.Action{Kind: ruleset.ActVerdict, Verdict: ruleset.Drop}, nil
	case "REJECT":
		return ruleset.Action{Kind: ruleset.ActVerdict, Verdict: ruleset.Reject}, nil
	case "RETURN":
		return ruleset.Action{Kind: ruleset.ActReturn}, nil
	case "LOG", "NFLOG", "ULOG", "TRACE", "CT", "NOTRACK", "MASQUERADE", "SNAT", "CONNMARK", "TCPMSS", "CHECKSUM":
		return ruleset.Action{Kind: ruleset.ActContinue, What: name}, nil
	case "DNAT", "REDIRECT":
		for _, o := range opts {
			if o.name != "--to-destination" && o.name != "--to-ports" {
				continue
			}
			v, err := arg(o)
			if err != nil {
				return ruleset.Action{}, err
			}
			if name == "REDIRECT" {
				rs, err := ports(v)
				if err != nil {
					return ruleset.Action{}, err
				}
				return ruleset.Action{Kind: ruleset.ActRedirect, DNATPort: rs[0].From, What: name}, nil
			}
			addr, port, err := dnatTarget(v, fam)
			if err != nil {
				return ruleset.Action{}, err
			}
			return ruleset.Action{Kind: ruleset.ActDNAT, DNATAddr: addr, DNATPort: port, What: name}, nil
		}
		return ruleset.Action{Kind: ruleset.ActUnknown, What: name + " without a destination"}, nil
	case "MARK":
		for _, o := range opts {
			v, err := arg(o)
			if err != nil {
				return ruleset.Action{}, err
			}
			val, mask, err := markValue(v)
			if err != nil {
				return ruleset.Action{}, err
			}
			switch o.name {
			case "--set-mark", "--set-xmark":
				// --set-xmark is (mark & ~mask) ^ value; equal to an OR when
				// value lies inside mask, which is how it is used in practice.
				return ruleset.Action{Kind: ruleset.ActSetMark, Mark: val, MarkMask: mask, What: name}, nil
			case "--or-mark":
				return ruleset.Action{Kind: ruleset.ActSetMark, Mark: val, What: name}, nil
			}
		}
		return ruleset.Action{Kind: ruleset.ActUnknown, What: "MARK " + optsString(opts)}, nil
	}
	// Anything else is a user chain or a target extension fwreach does not
	// know; Parse tells them apart once all chains of the table are known.
	kind := ruleset.ActJump
	if isGoto {
		kind = ruleset.ActGoto
	}
	return ruleset.Action{Kind: kind, Target: name}, nil
}

func optsString(opts []option) string {
	var parts []string
	for _, o := range opts {
		parts = append(parts, o.name+" "+strings.Join(o.args, " "))
	}
	return strings.Join(parts, " ")
}

func prefixes(v string, fam netpkt.Family) ([]netip.Prefix, error) {
	var out []netip.Prefix
	for _, s := range strings.Split(v, ",") {
		if !strings.Contains(s, "/") {
			a, err := netip.ParseAddr(s)
			if err != nil {
				return nil, fmt.Errorf("%w: address %q", ErrSyntax, s)
			}
			s += "/" + strconv.Itoa(a.BitLen())
		}
		p, err := netip.ParsePrefix(s)
		if err != nil {
			return nil, fmt.Errorf("%w: prefix %q", ErrSyntax, s)
		}
		if netpkt.FamilyOf(p.Addr()) != fam {
			return nil, fmt.Errorf("%w: %s is not %s", ErrSyntax, s, fam)
		}
		out = append(out, p.Masked())
	}
	return out, nil
}

func ports(v string) ([]ruleset.PortRange, error) {
	var out []ruleset.PortRange
	for _, s := range strings.Split(v, ",") {
		from, to, isRange := strings.Cut(s, ":")
		if !isRange {
			from, to, isRange = strings.Cut(s, "-")
		}
		a, err := strconv.ParseUint(from, 10, 16)
		if err != nil {
			return nil, fmt.Errorf("%w: port %q", ErrSyntax, s)
		}
		b := a
		if isRange {
			if b, err = strconv.ParseUint(to, 10, 16); err != nil {
				return nil, fmt.Errorf("%w: port %q", ErrSyntax, s)
			}
		}
		out = append(out, ruleset.PortRange{From: uint16(a), To: uint16(b)})
	}
	return out, nil
}

func markValue(v string) (uint32, uint32, error) {
	val, mask, hasMask := strings.Cut(v, "/")
	a, err := strconv.ParseUint(val, 0, 32)
	if err != nil {
		return 0, 0, fmt.Errorf("%w: mark %q", ErrSyntax, v)
	}
	m := uint64(0xffffffff)
	if hasMask {
		if m, err = strconv.ParseUint(mask, 0, 32); err != nil {
			return 0, 0, fmt.Errorf("%w: mark mask %q", ErrSyntax, v)
		}
	}
	return uint32(a), uint32(m), nil
}

// dnatTarget parses "ip[-ip][:port[-port]]", with IPv6 in brackets. Ranges
// collapse to their first element: fwreach follows one connection.
func dnatTarget(v string, fam netpkt.Family) (netip.Addr, uint16, error) {
	host, port := v, ""
	if strings.HasPrefix(v, "[") {
		end := strings.Index(v, "]")
		if end < 0 {
			return netip.Addr{}, 0, fmt.Errorf("%w: DNAT target %q", ErrSyntax, v)
		}
		host, port = v[1:end], strings.TrimPrefix(v[end+1:], ":")
	} else if fam == netpkt.IPv4 {
		host, port, _ = strings.Cut(v, ":")
	}
	host, _, _ = strings.Cut(host, "-")
	var addr netip.Addr
	if host != "" {
		a, err := netip.ParseAddr(host)
		if err != nil {
			return netip.Addr{}, 0, fmt.Errorf("%w: DNAT address %q", ErrSyntax, v)
		}
		addr = a
	}
	if port == "" {
		return addr, 0, nil
	}
	rs, err := ports(port)
	if err != nil {
		return netip.Addr{}, 0, err
	}
	return addr, rs[0].From, nil
}

// split tokenizes like iptables-save quotes: double quotes group words and
// backslash escapes the next character inside them.
func split(s string) ([]string, error) {
	var toks []string
	var cur strings.Builder
	inQuote, have := false, false
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case inQuote && c == '\\' && i+1 < len(s):
			i++
			cur.WriteByte(s[i])
		case c == '"':
			inQuote, have = !inQuote, true
		case !inQuote && (c == ' ' || c == '\t'):
			if have {
				toks = append(toks, cur.String())
				cur.Reset()
				have = false
			}
		default:
			cur.WriteByte(c)
			have = true
		}
	}
	if inQuote {
		return nil, fmt.Errorf("%w: unterminated quote in %q", ErrSyntax, s)
	}
	if have {
		toks = append(toks, cur.String())
	}
	return toks, nil
}
