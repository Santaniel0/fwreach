var testHost = &netpkt.Host{Ifaces: []netpkt.Iface{
	{Name: "eth0", Addrs: []netip.Prefix{netip.MustParsePrefix("203.0.113.10/24")}},
	{Name: "br-app", Addrs: []netip.Prefix{netip.MustParsePrefix("172.18.0.1/16")}},
}}

func TestParseRuleMatches(t *testing.T) {
	pkt := netpkt.NewInbound(netpkt.ProtoTCP, netip.MustParseAddr("198.51.100.7"), netip.MustParseAddr("203.0.113.10"), 5432, "eth0")
	dnated := pkt
	dnated.Dst, dnated.DstPort, dnated.DNATed, dnated.OutIface = netip.MustParseAddr("172.18.0.3"), 5432, true, "br-app"
	cases := []struct {
		spec string
		pkt  netpkt.Packet
		want netpkt.Tristate
	}{
		{"-p tcp -m tcp --dport 5432 -j DROP", pkt, netpkt.Yes},
		{"-p udp -m udp --dport 5432 -j DROP", pkt, netpkt.No},
		{"-p tcp -m tcp ! --dport 5432 -j DROP", pkt, netpkt.No},
		{"-p tcp -m multiport --dports 80,443,5000:6000 -j ACCEPT", pkt, netpkt.Yes},
		{"-s 10.0.0.0/8 -p tcp -m tcp --dport 5432 -j ACCEPT", pkt, netpkt.No},
		{"! -s 10.0.0.0/8 -j ACCEPT", pkt, netpkt.Yes},
		{"-i eth+ -j ACCEPT", pkt, netpkt.Yes},
		{"! -i eth0 -j ACCEPT", pkt, netpkt.No},
		{"-m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT", pkt, netpkt.No},
		{"-m conntrack --ctstate NEW -j ACCEPT", pkt, netpkt.Yes},
		{"-m state --state INVALID -j DROP", pkt, netpkt.No},
		{"-m addrtype --dst-type LOCAL -j DOCKER", pkt, netpkt.Yes},
		{"-m addrtype --dst-type BROADCAST -j DROP", pkt, netpkt.No},
		{"-p icmp -m icmp --icmp-type 8 -j ACCEPT", pkt, netpkt.No},
		{"-p tcp --syn -j ACCEPT", pkt, netpkt.Yes},
		{"-m comment --comment \"allow web\" -p tcp -j ACCEPT", pkt, netpkt.Yes},
		{"-m limit --limit 3/min --limit-burst 10 -j DROP", pkt, netpkt.Unknown},
		{"-m recent --rcheck --seconds 30 --hitcount 6 --name DEFAULT --mask 255.255.255.255 --rsource -j DROP", pkt, netpkt.Unknown},
		{"-p udp -m recent --set -j DROP", pkt, netpkt.No},
		{"-i eth0 -p tcp -m conntrack --ctorigdstport 5432 -j DROP", dnated, netpkt.Yes},
		{"-p tcp -m tcp --dport 5432 -j DROP", func() netpkt.Packet { p := dnated; p.DstPort = 8080; return p }(), netpkt.No},
		{"-m conntrack --ctorigdst 203.0.113.10 -j ACCEPT", dnated, netpkt.Yes},
		{"-m conntrack --ctstate DNAT -j ACCEPT", dnated, netpkt.Yes},
		{"-d 172.18.0.3/32 ! -i br-app -o br-app -p tcp -m tcp --dport 5432 -j ACCEPT", dnated, netpkt.Yes},
		{"-m mark --mark 0x1/0x1 -j ACCEPT", pkt, netpkt.No},
	}
	for _, tc := range cases {
		t.Run(tc.spec, func(t *testing.T) {
			r, err := ParseRule(tc.spec, netpkt.IPv4)
			if err != nil {
				t.Fatal(err)
			}
			if got := ruleset.EvalAll(r.Matches, &tc.pkt, testHost); got != tc.want {
				t.Fatalf("got %v, want %v", got, tc.want)
			}
		})
	}
}

func TestParseRuleTargets(t *testing.T) {
	cases := []struct {
		spec string
		want ruleset.Action
	}{
		{"-j ACCEPT", ruleset.Action{Kind: ruleset.ActVerdict, Verdict: ruleset.Accept}},
		{"-j REJECT --reject-with icmp-port-unreachable", ruleset.Action{Kind: ruleset.ActVerdict, Verdict: ruleset.Reject}},
		{"-j LOG --log-prefix \"[UFW BLOCK] \"", ruleset.Action{Kind: ruleset.ActContinue, What: "LOG"}},
		{"-g ufw-user-input", ruleset.Action{Kind: ruleset.ActGoto, Target: "ufw-user-input"}},
		{"! -i br0 -p tcp -m tcp --dport 8080 -j DNAT --to-destination 192.0.2.2:80",
			ruleset.Action{Kind: ruleset.ActDNAT, DNATAddr: netip.MustParseAddr("192.0.2.2"), DNATPort: 80, What: "DNAT"}},
		{"-p tcp -j REDIRECT --to-ports 3128", ruleset.Action{Kind: ruleset.ActRedirect, DNATPort: 3128, What: "REDIRECT"}},
		{"-j MARK --set-xmark 0x10/0xff", ruleset.Action{Kind: ruleset.ActSetMark, Mark: 0x10, MarkMask: 0xff, What: "MARK"}},
	}
	for _, tc := range cases {
		r, err := ParseRule(tc.spec, netpkt.IPv4)
		if err != nil {
			t.Fatalf("%s: %v", tc.spec, err)
		}
		if r.Action != tc.want {
			t.Errorf("%s: got %+v, want %+v", tc.spec, r.Action, tc.want)
		}
	}
	r, err := ParseRule("-p tcp -j DNAT --to-destination [2001:db8::2]:8080", netpkt.IPv6)
	if err != nil || r.Action.DNATAddr != netip.MustParseAddr("2001:db8::2") || r.Action.DNATPort != 8080 {
		t.Fatalf("ipv6 DNAT: %+v, %v", r.Action, err)
	}
}

const dump = `# Generated by iptables-nft-save v1.8.10 (nf_tables) on Mon Nov  9 10:12:03 2026
*nat
:PREROUTING ACCEPT [0:0]
:DOCKER - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
[12:720] -A DOCKER ! -i br-app -p tcp -m tcp --dport 8080 -j DNAT --to-destination 172.18.0.3:80
COMMIT
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:ufw-user-input - [0:0]
-A INPUT -j ufw-user-input
-A ufw-user-input -p tcp -m tcp --dport 22 -j ACCEPT
-A ufw-user-input -j SOMETHING
COMMIT
`

func TestParseDump(t *testing.T) {
	res, err := Parse(strings.NewReader(dump), netpkt.IPv4, 0)
	if err != nil {
		t.Fatal(err)
	}
	if res.Source != ruleset.SourceIPTablesNft || len(res.Warnings) != 0 {
		t.Fatalf("source %v warnings %v", res.Source, res.Warnings)
	}
	if len(res.Tables) != 2 {
		t.Fatalf("want 2 tables, got %d", len(res.Tables))
	}
	nat, filter := res.Tables[0], res.Tables[1]
	pre := nat.Chain("PREROUTING")
	if pre.Base == nil || pre.Base.Kind != ruleset.KindNAT || pre.Base.Priority != -100 || pre.Base.Hook != netpkt.Prerouting {
		t.Fatalf("nat PREROUTING base: %+v", pre.Base)
	}
	if nat.Chain("DOCKER").Base != nil {
		t.Fatal("user chain must not be a base chain")
	}
	if got := nat.Chain("DOCKER").Rules[0].Action.Kind; got != ruleset.ActDNAT {
		t.Fatalf("counter-prefixed rule parsed as %v", got)
	}
	if in := filter.Chain("INPUT"); in.Base.Policy != ruleset.Drop || in.Base.Priority != 0 {
		t.Fatalf("filter INPUT base: %+v", in.Base)
	}
	user := filter.Chain("ufw-user-input").Rules
	if user[0].Pos != 1 || user[1].Pos != 2 {
		t.Fatalf("positions: %d %d", user[0].Pos, user[1].Pos)
	}
	if user[1].Action.Kind != ruleset.ActUnknown {
		t.Fatalf("jump to a target that is not a chain must be unknown, got %+v", user[1].Action)
	}
}

func TestParseErrors(t *testing.T) {
	for _, in := range []string{
		"-A INPUT -j ACCEPT\n",
		"*filter\n-A NOPE -j ACCEPT\n",
		"*filter\n:INPUT MAYBE [0:0]\n",
		"*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -s 10.0.0.300 -j ACCEPT\n",
		"*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -m comment --comment \"open -j ACCEPT\n",
	} {
		if _, err := Parse(strings.NewReader(in), netpkt.IPv4, 0); !errors.Is(err, ErrSyntax) {
			t.Errorf("%q: want ErrSyntax, got %v", in, err)
		}
	}
}
